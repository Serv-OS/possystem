/** The icon name for a picture emoji, or null. Ignores the invisible emoji variation mark. */
export function emojiName(emoji) {
  if (!emoji) return null;
  return EMOJI_ICON[String(emoji).replace(/\uFE0F/g, '').trim()] || null;
}

/** Matches picture emoji (and the invisible emoji variation mark). Plain text marks such as the tick stay. */
export const EMOJI_RE = /(?:[\u{1F1E6}-\u{1F1FF}]{2}|[\u{1F300}-\u{1FAFF}\u{1F000}-\u{1F2FF}]|[\u2600-\u26FF\u2700-\u27BF\u2B50\u2B55\u231A\u231B\u23E9-\u23FA](?=\uFE0F))\uFE0F?|[\u26A0\u2705\u274C\u2753\u2B50\u26D4\u2615\u26A1\u2699\u2696\u2709\u270F\u270D\u270B\u2611\u2744\u2600\u2764\u263E\u23F3\u231B\u23F1\u23F0]\uFE0F?|\u21A9\uFE0F/gu;

/** Text with picture emoji taken out, for places that can only hold text (toasts, options, texts). */
export function stripEmoji(text) {
  if (text == null) return text;
  return String(text).replace(EMOJI_RE, '').replace(/\u200D|\u20E3/g, '').replace(/[ \t]{2,}/g, ' ').replace(/^ +| +$/gm, '');
}

// ----- module state + subscribers -----
/** The language a kiosk starts in: the stored one when it is still offered, else English. */
export function startupLanguage(stored) {
  if (stored && STRINGS[stored] && !RETIRED_LANGUAGES.includes(stored)) return stored;
  return DEFAULT_LANG;
}

let _lang = (() => {
  try {
    const stored = typeof localStorage !== 'undefined' && localStorage.getItem(STORAGE_KEY);
    return startupLanguage(stored);
  } catch { /* localStorage may be blocked */ }
  return DEFAULT_LANG;
})();

const _subs = new Set();

export function getLang() {
  return _lang;
}

export function setLang(code) {
  if (!STRINGS[code]) {
    console.warn('[i18n] unknown language code, ignoring:', code);
    return;
  }
  if (code === _lang) return;
  _lang = code;
  try { localStorage.setItem(STORAGE_KEY, code); } catch { /* noop */ }
  _subs.forEach(fn => { try { fn(); } catch (e) { console.error('[i18n] subscriber threw', e); } });
}

export function t(key, lang) {
  const useLang = lang || _lang;
  const langDict = STRINGS[useLang] || STRINGS[DEFAULT_LANG];
  if (langDict && langDict[key] != null) return langDict[key];
  // Fall back to English
  const enDict = STRINGS[DEFAULT_LANG] || {};
  if (enDict[key] != null) return enDict[key];
  // Loud fallback: return raw key so missing strings are visible
  return key;
}

/**
 * t() with {name} values filled in. A value that is not passed keeps its {name} marker,
 * so a missing value is visible rather than silently blank.
 */
export function tf(key, vars = {}, lang) {
  return String(t(key, lang)).replace(/\{(\w+)\}/g, (m, k) => (vars?.[k] ?? m));
}

/** Plural: base + '.one' when n is 1, otherwise base + '.other', with {n} filled in. */
export function tn(base, n, vars = {}, lang) {
  return tf(base + (n === 1 ? '.one' : '.other'), { n, ...vars }, lang);
}

/** Every English key starting with prefix (for tests). */
export function englishKeys(prefix = '') {
  return Object.keys(STRINGS[DEFAULT_LANG]).filter(k => k.startsWith(prefix));
}

/** Every key a language has its OWN text for (no English fallback), starting with prefix (for tests). */
export function languageKeys(code, prefix = '') {
  return Object.keys(STRINGS[code] || {}).filter(k => k.startsWith(prefix));
}

export function getLanguageMeta(code) {
  return LANGUAGES.find(l => l.code === code) || LANGUAGES[0];
}

// ----- React hook -----
// Causes the calling component to re-render when language changes.
// Uses useSyncExternalStore (the React 18+ idiom for subscribing
// React renders to a non-React store), which sidesteps the
// set-state-in-effect class of warnings + races on mount.
function _subscribe(fn) {
  _subs.add(fn);
  return () => { _subs.delete(fn); };
}
function _getSnapshot() { return _lang; }
export function useKioskLang() {
  return useSyncExternalStore(_subscribe, _getSnapshot, _getSnapshot);
}
